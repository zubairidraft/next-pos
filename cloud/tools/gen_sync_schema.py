#!/usr/bin/env python3
"""Generates the cloud sync schema from the PC database migrations.

  * crates/pos-core/src/db/migrations/V12__cloud_changes.sql
      SQLite triggers that note every change of a synced table (only while
      the shop is linked to the cloud), so the PC can send it later.
  * cloud/supabase/migrations/0002_mirror.sql
      The same tables on the server (one copy per shop) and the functions that
      store what a shop sends.

Run it again whenever a migration adds a table or a column:
    python3 cloud/tools/gen_sync_schema.py
"""
import glob
import os
import re
import sqlite3

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
MIG = os.path.join(ROOT, "crates", "pos-core", "src", "db", "migrations")

# Tables the server gets. Anything not listed never leaves the PC
# (app settings with keys, phone secrets, backups list, held carts, ...).
SYNC = [
    "apparel_matrices", "audit_log", "barcodes", "brands", "business_settings", "cash_sessions",
    "categories", "claims", "document_revisions", "inventory_balances", "invoice_allocations",
    "parties", "party_ledger", "payments", "price_lists", "prices", "product_serials",
    "product_variants", "products", "purchase_lines", "purchase_return_lines", "purchase_returns",
    "purchases", "sale_lines", "sale_return_lines", "sale_returns", "sales", "stock_count_lines",
    "stock_count_sessions", "stock_movements", "tax_rates", "units", "users", "variant_units",
]
# Columns that must never leave the PC.
SECRET = {"users": {"password_hash", "pin_hash", "failed_attempts", "locked_until", "last_login_at"}}


def load_schema():
    c = sqlite3.connect(":memory:")
    files = [f for f in glob.glob(os.path.join(MIG, "V*.sql")) if "cloud_changes" not in f]
    files.sort(key=lambda f: int(re.match(r"V(\d+)", os.path.basename(f)).group(1)))
    for f in files:
        c.executescript(open(f, encoding="utf-8").read())
    out = {}
    for t in SYNC:
        cols = c.execute(f"pragma table_info({t})").fetchall()
        if not cols:
            raise SystemExit(f"table {t} not found")
        pk = [x[1] for x in cols if x[5] > 0]
        if len(pk) != 1:
            raise SystemExit(f"table {t}: synced tables need a single-column primary key")
        keep = [(x[1], (x[2] or "TEXT").upper()) for x in cols if x[1] not in SECRET.get(t, set())]
        out[t] = (pk[0], keep)
    return out


def sqlite_triggers(schema):
    s = [
        "-- V12: notes every change of a synced table while the shop is linked to the cloud.",
        "-- Generated by cloud/tools/gen_sync_schema.py. Do not edit by hand.",
        "CREATE TABLE IF NOT EXISTS cloud_changes (",
        "    seq INTEGER PRIMARY KEY AUTOINCREMENT,",
        "    tbl TEXT NOT NULL,",
        "    pk TEXT NOT NULL,",
        "    op TEXT NOT NULL CHECK(op IN ('u', 'd'))",
        ");",
        "",
    ]
    on = "(SELECT value FROM app_settings WHERE key = 'cloud.enabled') = '1'"
    for t, (pk, _) in schema.items():
        s += [
            f"CREATE TRIGGER IF NOT EXISTS cloud_{t}_ins AFTER INSERT ON {t} WHEN {on}",
            f"BEGIN INSERT INTO cloud_changes (tbl, pk, op) VALUES ('{t}', NEW.{pk}, 'u'); END;",
            f"CREATE TRIGGER IF NOT EXISTS cloud_{t}_upd AFTER UPDATE ON {t} WHEN {on}",
            f"BEGIN",
            f"    INSERT INTO cloud_changes (tbl, pk, op) SELECT '{t}', OLD.{pk}, 'd' WHERE OLD.{pk} IS NOT NEW.{pk};",
            f"    INSERT INTO cloud_changes (tbl, pk, op) VALUES ('{t}', NEW.{pk}, 'u');",
            f"END;",
            f"CREATE TRIGGER IF NOT EXISTS cloud_{t}_del AFTER DELETE ON {t} WHEN {on}",
            f"BEGIN INSERT INTO cloud_changes (tbl, pk, op) VALUES ('{t}', OLD.{pk}, 'd'); END;",
            "",
        ]
    return "\n".join(s)


def pg_type(t):
    if "INT" in t:
        return "bigint"
    if "REAL" in t or "FLOA" in t or "DOUB" in t:
        return "double precision"
    return 'text COLLATE "C"'


def pg_mirror(schema):
    """Compact form: the table list as JSON, and one block that builds the
    tables (one copy per shop) and their store / delete functions from it."""
    import json
    spec = {t: {"pk": pk, "cols": [[n, pg_type(ty)] for n, ty in cols]} for t, (pk, cols) in schema.items()}
    body = json.dumps(spec, separators=(",", ":"))
    return """-- Mirror of each shop's PC tables (read-only copy for reports).
-- Generated by cloud/tools/gen_sync_schema.py. Do not edit by hand.
CREATE SCHEMA IF NOT EXISTS mirror;
REVOKE ALL ON SCHEMA mirror FROM PUBLIC;

CREATE OR REPLACE FUNCTION mirror.synced_spec() RETURNS jsonb LANGUAGE sql IMMUTABLE AS $spec$
  SELECT '""" + body.replace("'", "''") + """'::jsonb;
$spec$;

CREATE OR REPLACE FUNCTION mirror.synced_tables() RETURNS text[] LANGUAGE sql IMMUTABLE AS $f$
  SELECT array_agg(k ORDER BY k) FROM jsonb_object_keys(mirror.synced_spec()) k;
$f$;

DO $gen$
DECLARE t text; d jsonb; pk text; coldefs text; names text; rnames text; sets text; c jsonb;
BEGIN
  FOR t, d IN SELECT key, value FROM jsonb_each(mirror.synced_spec()) LOOP
    pk := d->>'pk';
    SELECT string_agg(format('%I %s', x->>0, x->>1), ', '), string_agg(format('%I', x->>0), ', '),
           string_agg(format('r.%I', x->>0), ', '),
           string_agg(format('%I = EXCLUDED.%I', x->>0, x->>0), ', ') FILTER (WHERE x->>0 <> pk)
      INTO coldefs, names, rnames, sets FROM jsonb_array_elements(d->'cols') x;
    EXECUTE format('CREATE TABLE IF NOT EXISTS mirror.%I (shop_id uuid NOT NULL, %s, PRIMARY KEY (shop_id, %I))', t, coldefs, pk);
    -- columns added by later PC versions
    FOR c IN SELECT * FROM jsonb_array_elements(d->'cols') LOOP
      EXECUTE format('ALTER TABLE mirror.%I ADD COLUMN IF NOT EXISTS %I %s', t, c->>0, c->>1);
    END LOOP;
    EXECUTE format($q$CREATE OR REPLACE FUNCTION mirror.%I(p_shop uuid, p_rows jsonb) RETURNS void LANGUAGE sql AS $b$
      INSERT INTO mirror.%I (shop_id, %s)
      SELECT DISTINCT ON (r.%I) p_shop, %s FROM jsonb_populate_recordset(NULL::mirror.%I, p_rows) r
      ON CONFLICT (shop_id, %I) DO %s;
    $b$$q$, '_up_' || t, t, names, pk, rnames, t, pk, CASE WHEN sets IS NULL THEN 'NOTHING' ELSE 'UPDATE SET ' || sets END);
    EXECUTE format($q$CREATE OR REPLACE FUNCTION mirror.%I(p_shop uuid, p_keys jsonb) RETURNS void LANGUAGE sql AS $b$
      DELETE FROM mirror.%I WHERE shop_id = p_shop AND %I IN (SELECT jsonb_array_elements_text(p_keys));
    $b$$q$, '_del_' || t, t, pk);
  END LOOP;
END $gen$;
"""


def rust_table_list(schema):
    lines = ["// Generated by cloud/tools/gen_sync_schema.py. Do not edit by hand.",
             "/// (table, primary key, columns sent to the cloud)",
             "pub(crate) const SYNC_TABLES: &[(&str, &str, &[&str])] = &["]
    for t, (pk, cols) in schema.items():
        lines.append(f'    ("{t}", "{pk}", &[' + ", ".join(f'"{c}"' for c, _ in cols) + "]),")
    lines.append("];")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    sch = load_schema()
    open(os.path.join(MIG, "V12__cloud_changes.sql"), "w", encoding="utf-8").write(sqlite_triggers(sch))
    open(os.path.join(ROOT, "cloud", "supabase", "migrations", "0002_mirror.sql"), "w", encoding="utf-8").write(pg_mirror(sch))
    open(os.path.join(ROOT, "crates", "pos-core", "src", "cloud_tables.rs"), "w", encoding="utf-8").write(rust_table_list(sch))
    print(f"{len(sch)} tables")
